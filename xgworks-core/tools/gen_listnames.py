"""Generate src/listnames_data.rs: the SysEx parameter-name tables XGworks'
List window uses to name XG / MU Parameter Change events.

XGworks.exe keeps one 128-entry `char*` table per address block, indexed by
the low address byte (file 0x309880.. for XG, 0x30b610.. for MU)."""
import struct

b = open(r'F:\rea\XG4\XGworks.exe', 'rb').read()
pe = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, pe + 6)[0]
opt = struct.unpack_from('<H', b, pe + 20)[0]
base = struct.unpack_from('<I', b, pe + 24 + 28)[0]
secs = []
for i in range(nsec):
    o = pe + 24 + opt + 40 * i
    vs, va, rs_, ra = struct.unpack_from('<IIII', b, o + 8)
    secs.append((va, vs, ra, rs_))


def v2f(v):
    for va, vs, ra, rs_ in secs:
        if base + va <= v < base + va + rs_:
            return v - base - va + ra


def s(p):
    f = v2f(p)
    if f is None:
        return ''
    e = b.find(b'\0', f, f + 64)
    return b[f:e].decode('latin1')


def table(off):
    return [s(p) for p in struct.unpack_from('<128I', b, off)]


def esc(x):
    return '"' + x.replace('\\', '\\\\').replace('"', '\\"') + '"'


# (rust name, file offset, comment)
XG = [
    ('XG_SYS', 0x309880, '00 00 ll  System'),
    ('XG_SYS_INF', 0x309a80, '00 01 ll  System Information'),
    ('XG_EFCT1', 0x309c80, '02 01 ll  Effect 1 (reverb / chorus / variation)'),
    ('XG_EQ', 0x309e80, '02 40 ll  Multi EQ'),
    ('XG_EFCT2', 0x30a080, '03 nn ll  Effect 2 (insertion nn)'),
    ('XG_PART', 0x30a280, '08 nn ll  Multi Part'),
    ('XG_VL_PART', 0x30a480, '09 nn ll  VL-XG Part'),
    ('XG_PART2', 0x30a680, '0A nn ll  Multi Part (additional)'),
    ('XG_AUDIO', 0x30a880, '10 nn ll  A/D Part'),
    ('XG_AUDIO_CFG', 0x30aa80, '11 00 ll  A/D Setup'),
    ('XG_AUDIO2', 0x30ac80, '12? nn ll A/D output'),
    ('XG_DRUM', 0x30ae80, '3n rr ll  Drum Setup n+1, note rr'),
]
MU = [
    ('MU_SYS', 0x30b610, '00 00 ll  System'),
    ('MU_PRF', 0x30b810, '09 00 ll  Current Performance Common'),
    ('MU_PRF_PRT', 0x30ba10, '09 01 ll  Current Performance Part'),
    ('MU_REMOTE', 0x30bc10, '0A 00 ll  Remote Switch'),
    ('MU_INT_PRF', 0x30be10, '30 pp ll  Internal Performance Common'),
    ('MU_INT_PRF_PRT', 0x30c010, '3n pp ll  Internal Performance Part n'),
]

out = ['//! SysEx parameter names of XGworks\' List window, per address block, indexed',
       '//! by the low address byte. Extracted from XGworks.exe (`char*[128]` tables',
       '//! at file 0x309880.. / 0x30b610..). Generated by tools/gen_listnames.py.', '', '#![allow(dead_code)]', '']
for name, off, cmt in XG + MU:
    t = table(off)
    out.append(f'/// {cmt}')
    out.append('#[rustfmt::skip]')
    out.append(f'pub static {name}: [&str; 128] = [' + ', '.join(esc(x) for x in t) + '];')
# effect type names: (code = MSB << 7 | LSB, char*) pairs, file 0x3004e8..0x300ca0
fx = {}
a = 0x3004e8
while a < 0x300ca0:
    c, ptr = struct.unpack_from('<II', b, a)
    a += 8
    if ptr and c not in fx:
        fx[c] = s(ptr)
out.append('/// Effect type names by `MSB << 7 | LSB` (reverb / chorus / variation / insertion).')
out.append('#[rustfmt::skip]')
out.append('pub static FX_TYPE_NAMES: [(u16, &str); %d] = [' % len(fx) + ', '.join('(0x%04X, %s)' % (c, esc(n)) for c, n in sorted(fx.items())) + '];')
open(r'F:\rea\xgworks-core\src\listnames_data.rs', 'w', newline='\n').write('\n'.join(out) + '\n')
for name, off, _ in XG + MU:
    t = table(off)
    print(name, [(hex(i), x) for i, x in enumerate(t) if x][:6])
