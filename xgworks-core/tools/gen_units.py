import struct

b = open(r'F:\rea\XG4\XGworks.exe', 'rb').read()
pe = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, pe + 6)[0]
opt = struct.unpack_from('<H', b, pe + 20)[0]
base = struct.unpack_from('<I', b, pe + 24 + 28)[0]
secs = []
for i in range(nsec):
    o = pe + 24 + opt + 40 * i
    vs, va, rs_, ra = struct.unpack_from('<IIII', b, o + 8)
    secs.append((va, vs, ra, rs_))


def v2f(v):
    for va, vs, ra, rs_ in secs:
        if base + va <= v < base + va + rs_:
            return v - base - va + ra


def s(p):
    f = v2f(p)
    if f is None:
        return ''
    e = b.find(b'\0', f, f + 64)
    return b[f:e].decode('latin1')


BS = chr(92)
DQ = chr(34)


def rs(x):
    return DQ + x.replace(BS, BS + BS).replace(DQ, BS + DQ) + DQ


tbl = {1: 0x707c98, 2: 0x707e98, 3: 0x708098, 4: 0x708298, 5: 0x708498, 6: 0x708698, 7: 0x708898,
       8: 0x708a98, 9: 0x708c58, 10: 0x708e58, 11: 0x709058, 12: 0x709258, 13: 0x709458,
       14: 0x7010c0, 15: 0x7002c0, 16: 0x709658, 17: 0x709858, 18: 0x709a58}
extra = {'NOTE_NAMES': 0x700ac0, 'PAN_RANDOM': 0x7004c0}


def table(a):
    vals = []
    for j in range(128):
        p = struct.unpack_from('<I', b, v2f(a + 4 * j))[0]
        vals.append(s(p) if 0x770000 <= p < 0x7a0000 else '')
    return vals


out = ['//! Display tables extracted from XGworks.exe (`FUN_00601e93` @0x601e93, used by',
       '//! `CPrmStr`): value tables 1..18 indexed by the raw parameter value, and the',
       '//! per-effect-type parameter descriptors (47 types x 16 params) at 0x701e98.',
       '//! Generated by tools/gen_units.py — do not edit by hand.', '',
       '#[rustfmt::skip]', 'pub static TABLES: [&[&str]; 19] = [', '    &[],']
for n in range(1, 19):
    out.append('    &[' + ', '.join(rs(v) for v in table(tbl[n])) + '],')
out.append('];')
for name, a in extra.items():
    out.append('#[rustfmt::skip]')
    out.append('pub static %s: [&str; 128] = [%s];' % (name, ', '.join(rs(v) for v in table(a))))
out.append('')
out.append('/// (name, min, max, kind, offset, divisor, table, unit-or-enum-key)')
out.append("pub type Desc = (&'static str, u16, u16, u8, i16, u16, u8, &'static str);")
out.append('#[rustfmt::skip]')
out.append('pub static FX_DESC: [[Desc; 16]; 47] = [')
a = 0x701e98
for t in range(47):
    out.append('    [')
    for k in range(16):
        d = struct.unpack_from('<8I', b, v2f(a))
        a += 32
        off = struct.unpack('<i', struct.pack('<I', d[4]))[0]
        out.append('        (%s, %d, %d, %d, %d, %d, %d, %s),' % (rs(s(d[0])), d[1], d[2], d[3], off, d[5], d[6], rs(s(d[7]))))
    out.append('    ],')
out.append('];')
open(r'F:\rea\xgworks-core\src\xgunits_data.rs', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('ok', len(out))
