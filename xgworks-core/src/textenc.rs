/// Song text bytes → string (UTF-8 if valid, else Windows-1250).
pub fn decode(b: &[u8]) -> String {
    if b.iter().all(|&c| c < 0x80) {
        return b.iter().map(|&c| c as char).collect();
    }
    match std::str::from_utf8(b) {
        Ok(s) => s.to_string(),
        Err(_) => b.iter().map(|&c| if c < 0x80 { c as char } else { char::from_u32(CP1250[c as usize - 0x80] as u32).unwrap_or('?') }).collect(),
    }
}

/// String → song text bytes (Windows-1250 if every character fits, else UTF-8).
pub fn encode(s: &str) -> Vec<u8> {
    let mut out = Vec::with_capacity(s.len());
    for ch in s.chars() {
        let u = ch as u32;
        if u < 0x80 {
            out.push(u as u8);
        } else if let Some(i) = CP1250.iter().position(|&x| x as u32 == u) {
            out.push(0x80 + i as u8);
        } else {
            return s.as_bytes().to_vec();
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn czech_names_round_trip() {
        let w = encode("Křídla z mýdla");
        assert_eq!(w[1], 0xF8, "ř in Windows-1250");
        assert_eq!(decode(&w), "Křídla z mýdla");
        assert_eq!(decode("Křídla".as_bytes()), "Křídla", "UTF-8 stays UTF-8");
        assert_eq!(encode("日本"), "日本".as_bytes(), "not in 1250: UTF-8");
        assert_eq!(decode(b"Bass"), "Bass");
    }
}
